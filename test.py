#!/usr/bin/env python3
from mininet.net import Mininet
from mininet.topo import Topo
from mininet.link import TCLink
from mininet.node import OVSBridge
from mininet.cli import CLI
from mininet.log import setLogLevel
import subprocess

class MyTopo(Topo):
    def build(self):
        client1 = self.addHost('C1', ip='192.168.0.2/24', defaultRoute='via 192.168.0.1')
        client2 = self.addHost('C2', ip='192.168.0.3/24', defaultRoute='via 192.168.0.1')
        client3 = self.addHost('C3', ip='192.168.0.4/24', defaultRoute='via 192.168.0.1')
        client4 = self.addHost('C4', ip='192.168.0.5/24', defaultRoute='via 192.168.0.1')
        client5 = self.addHost('C5', ip='192.168.0.6/24', defaultRoute='via 192.168.0.1')
        client6 = self.addHost('C6', ip='192.168.0.7/24', defaultRoute='via 192.168.0.1')
        client7 = self.addHost('C7', ip='192.168.0.8/24', defaultRoute='via 192.168.0.1')
        client8 = self.addHost('C8', ip='192.168.0.9/24', defaultRoute='via 192.168.0.1')
        client9 = self.addHost('C9', ip='192.168.0.10/24', defaultRoute='via 192.168.0.1')
        server1 = self.addHost('S1', ip='192.168.1.2/24', defaultRoute='via 192.168.1.1')
        server2 = self.addHost('S2', ip='192.168.1.3/24', defaultRoute='via 192.168.1.1')
        server3 = self.addHost('S3', ip='192.168.1.4/24', defaultRoute='via 192.168.1.1')
        clientRouter = self.addHost('CR', ip='192.168.0.1/24')
        serverRouter = self.addHost('SR', ip='192.168.1.1/24')
        # self.addLink(client, clientRouter, intfName1='eth0', intfName2='eth0')
        self.addLink(client1, clientRouter)
        self.addLink(client2, clientRouter)
        self.addLink(client3, clientRouter)
        self.addLink(client4, clientRouter)
        self.addLink(client5, clientRouter)
        self.addLink(client6, clientRouter)
        self.addLink(client7, clientRouter)
        self.addLink(client8, clientRouter)
        self.addLink(client9, clientRouter)
        self.addLink(server1, serverRouter)
        self.addLink(server2, serverRouter)
        self.addLink(server3, serverRouter)
        self.addLink(clientRouter, serverRouter, intfName1='eth1', intfName2='eth1', params1={'ip':'10.1.1.1/24'}, params2={'ip':'10.1.1.2/24'})
        self.addLink(clientRouter, serverRouter, intfName1='eth2', intfName2='eth2', params1={'ip':'10.1.2.1/24'}, params2={'ip':'10.1.2.2/24'})

if __name__ == '__main__':
    setLogLevel('info')
    print('##### Phase 1: Loading topology #####')
    net = Mininet(topo=MyTopo(), link=TCLink,
                  switch=OVSBridge, controller=None)
    net.start()
    print('##### Phase 2: Bootstrap #####')
    client, server = net.get('C', 'S')
    clientRouter, serverRouter = net.get('CR', 'SR')
    clientRouter.cmd('nft flush ruleset')
    clientRouter.cmd('nft add table ip spray')
    clientRouter.cmd('nft add chain ip spray pre \'{ type filter hook prerouting priority mangle; }\'')
    clientRouter.cmd('nft add chain ip spray forward \'{ type filter hook forward priority mangle; }\'')
    clientRouter.cmd('nft add rule ip spray forward meta mark 1 counter')
    clientRouter.cmd('nft add rule ip spray forward oifname "eth1" counter')
    clientRouter.cmd('nft add rule ip spray forward meta mark 2 counter')
    clientRouter.cmd('nft add rule ip spray forward oifname "eth2" counter')
    
    clientRouter.cmd('ip route add default via 10.1.2.2')
    clientRouter.cmd('ip rule del table 101')
    clientRouter.cmd('ip route flush table 101')
    clientRouter.cmd('ip rule add fwmark 1 table 101')
    clientRouter.cmd('ip route add default via 10.1.1.2 dev eth1 table 101')
    clientRouter.cmd('ip rule del table 102')
    clientRouter.cmd('ip route flush table 102')
    clientRouter.cmd('ip rule add fwmark 2 table 102')
    clientRouter.cmd('ip route add default via 10.1.2.2 dev eth2 table 102')
    
    clientRouter.cmd('for interface in /proc/sys/net/ipv4/conf/*/rp_filter; do echo 0 >$interface; done')
    clientRouter.cmd('for interface in /proc/sys/net/ipv6/conf/*/disable_ipv6; do echo 1 >$interface; done')
    clientRouter.cmd('sysctl -w net.ipv4.ip_forward=1')
    
    serverRouter.cmd('ip route add default via 10.1.2.1')

    serverRouter.cmd('for interface in /proc/sys/net/ipv4/conf/*/rp_filter; do echo 0 >$interface; done')
    serverRouter.cmd('for interface in /proc/sys/net/ipv6/conf/*/disable_ipv6; do echo 1 >$interface; done')
    serverRouter.cmd('sysctl -w net.ipv4.ip_forward=1')
    print('##### Phase 3: Base line sanity check (no packet spraying) #####')
    server.cmd('iperf3 -s -D')
    clientRouter.cmd('nft reset ruleset')
    print('Client pings server 10 times')
    client.cmd('ping -i 0.02 192.168.1.2 -c10')
    clientRouter.cmd('nft list ruleset | grep -E \'oifname.*counter\'')
    print('Packets should all land on 1 outbound interface')
    print(clientRouter.cmd('nft list ruleset | grep -E \'oifname.*counter\''))
    print('##### Phase 4: Base line iperf #####')
    print(client.cmd('iperf3 -c 192.168.1.2 -i 0 -P1 -C cubic'))
    print(client.cmd('iperf3 -c 192.168.1.2 -i 0 -P1 -C bbr'))
    print('##### Phase 5: Test sanity check (packet spraying) #####')
    clientRouter.cmd('nft add rule ip spray pre iifname "eth0" meta mark set numgen inc mod 2 offset 1')
    clientRouter.cmd('nft reset rules table ip spray')
    print('Client pings server 10 times')
    client.cmd('ping -i 0.02 192.168.1.2 -c10')
    print('Packets should spread evenly on outbound interfaces')
    print(clientRouter.cmd('nft list ruleset | grep -E \'oifname.*counter\''))
    print('##### Phase 6: Test spray iperf #####')
    print(client.cmd('iperf3 -c 192.168.1.2 -i 0 -P1 -C cubic'))
    print(client.cmd('iperf3 -c 192.168.1.2 -i 0 -P1 -C bbr'))
    CLI(net)
    net.stop()
